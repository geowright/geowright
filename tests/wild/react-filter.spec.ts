import { cartoBasemap } from './basemap';
import { expect, test, type Routes } from './harness';

// visgl/react-map-gl example "filter" (React 18 + react-map-gl 8): the map instance is owned by the wrapper
// (hook via onLoad => registered LATE, after the style has loaded), the <Source> has NO id (the wrapper
// generates "jsx-source-0"), features have no ids and carry a large nested `flows` object.
// Hovering a county highlights it through a layer filter and shows a React-rendered Popup.
const routes: Routes = [
  ...cartoBasemap('positron', [-98, 38.88]),
  ['https://raw.githubusercontent.com/visgl/deck.gl-data/refs/heads/master/examples/arc/counties.json', 'react-map-gl/counties.KS-NE-OK.json'],
];
const APP = '/apps/react-map-gl/filter/';

test.describe('wild: react-map-gl / filter', () => {
  test('counties are addressable by name although neither the source nor the features have ids', async ({ wild }) => {
    const map = await wild.open(APP, { routes });
    await expect(map.features({ layer: 'counties' })).toHaveFeatureCount(275);
    const seward = await map.feature({ layer: 'counties', where: { name: 'Seward, KS' } }).info();
    expect(seward.id).toBeUndefined();
    expect((await map.layers()).find((l) => l.id === 'counties')!.source).toMatch(/^jsx-source-\d+$/); // generated by the wrapper
    // the app inserts its layers beneath the basemap's label layer
    const order = (await map.layers()).map((l) => l.id);
    expect(order.indexOf('counties-highlighted')).toBeLessThan(order.indexOf('waterway_label'));
  });

  test('hovering a county highlights it and shows its name in a popup at the pointer', async ({ wild }) => {
    const map = await wild.open(APP, { routes });
    await expect(map).not.toHaveFeature({ layer: 'counties-highlighted' });
    const cherry = map.feature({ layer: 'counties', where: { name: 'Cherry, NE' } });
    const at = await cherry.lngLat();
    await cherry.hover();
    await expect(map).toHaveFeature({ layer: 'counties-highlighted', where: { name: 'Cherry, NE' } });
    await expect(map.features({ layer: 'counties-highlighted' })).toHaveFeatureCount(1);
    await expect(map).toHavePopup({ at, text: 'Cherry', tolerancePx: 14 }); // Popup offset [0, -10]
  });

  test('the highlight filter is a substring match: hovering Seward, KS also lights up Seward, NE (the app\'s behaviour, asserted as is)', async ({ wild }) => {
    const map = await wild.open(APP, { routes });
    await map.feature({ layer: 'counties', where: { name: 'Seward, KS' } }).hover();
    await expect(map.features({ layer: 'counties-highlighted', where: { name: /^Seward, / } })).toHaveFeatureCount(2);
  });

  test('moving off the counties clears highlight and popup', async ({ wild }) => {
    const map = await wild.open(APP, { routes });
    await map.feature({ layer: 'counties', where: { name: 'Cherry, NE' } }).hover();
    await expect(map).toHavePopup({ text: 'Cherry' });
    await map.hoverAt({ lng: -112, lat: 45 }); // Montana: not in the fixture
    await expect(map).not.toHavePopup();
    await expect(map).not.toHaveFeature({ layer: 'counties-highlighted' });
  });

  test('the snapshot copes with a production-sized basemap, generated ids and nested properties', async ({ wild }) => {
    const map = await wild.open(APP, { routes });
    const snap = await map.snapshot({ layers: ['counties'], perLayer: 2 });
    expect(snap).toMatch(/\[counties\] 275 fill entities/);
    expect(snap).toMatch(/- Polygon @\(\d+,\d+\).* name="\w+, (KS|NE|OK)" flows=\{"/);
    expect(snap).not.toContain('[object Object]');
  });
});
