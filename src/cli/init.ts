/**
 * `npx geowright init` — the first five minutes. Writes a fixture, the software-WebGL launch flags and a first
 * spec that prints `map.snapshot()` (the fastest way to learn an app's layer ids and properties without reading its
 * code), and prints the ONE line the app needs, in the form that the map wrapper in use requires.
 * No dependencies, no network, never overwrites a file without --force.
 */
export interface Wrapper {
  /** npm package that identifies it. */
  pkg: string;
  name: string;
  /** Where the line goes, and the line. */
  hook: { where: string; code: string }[];
  note?: string;
}

