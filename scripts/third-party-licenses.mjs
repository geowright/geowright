#!/usr/bin/env node
// Writes dist/THIRD_PARTY_LICENSES.txt: the license text of every npm package whose code esbuild
// actually put into the injected bundles (dist/inpage.js, dist/inpage-agent.js). Derived from
// esbuild's metafile, so it cannot drift from the bundle: tree-shaken packages are not listed,
// newly bundled ones appear by themselves. The Node-side bundles use --packages=external and
// bundle nothing. Fails if a bundled package has no license file (then decide by hand).
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entries = ['src/inpage/index.ts', 'src/inpage/agent-entry.ts'];

const result = await build({
  entryPoints: entries.map((e) => join(root, e)),
  bundle: true, format: 'iife', target: 'es2022', write: false, metafile: true,
  outdir: join(root, 'dist/.licenses-scan'), absWorkingDir: root, logLevel: 'silent',
});

const packages = new Map(); // package dir -> bytes that survived tree-shaking
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, { bytesInOutput }] of Object.entries(output.inputs)) {
    const at = input.lastIndexOf('node_modules/');
    if (at < 0 || bytesInOutput === 0) continue;
    const rest = input.slice(at + 'node_modules/'.length).split('/');
    const name = rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0];
    // A package may vendor its own dependencies pre-built (style-spec: dist/node_modules/quickselect/index.mjs,
    // no package.json there): the license then comes from the installed copy of the same package.
    let dir = join(root, input.slice(0, at), 'node_modules', name);
    if (!existsSync(join(dir, 'package.json'))) dir = join(root, 'node_modules', name);
    if (!existsSync(join(dir, 'package.json'))) {
      console.error(`third-party-licenses: ${input} is bundled but "${name}" is not installed — add its license by hand`);
      process.exit(1);
    }
    packages.set(dir, (packages.get(dir) ?? 0) + bytesInOutput);
  }
}

const sections = [];
for (const dir of [...packages.keys()].sort()) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));
  if (!file || !existsSync(join(dir, file))) {
    console.error(`third-party-licenses: ${pkg.name} is bundled but ships no license file — add it by hand`);
    process.exit(1);
  }
  const licence = typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license);
  sections.push(
    `${'='.repeat(80)}\n${pkg.name} ${pkg.version} — ${licence}\n` +
    `${pkg.homepage ?? pkg.repository?.url ?? ''}\n${'='.repeat(80)}\n\n` +
    readFileSync(join(dir, file), 'utf8').trim() + '\n',
  );
}

const header =
  'geowright — third-party software bundled into dist/inpage.js and dist/inpage-agent.js\n' +
  '(the scripts injected into the page under test). Generated by scripts/third-party-licenses.mjs\n' +
  'from the bundler\'s own input list. geowright itself is licensed under Apache-2.0: see LICENSE.\n\n';
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/THIRD_PARTY_LICENSES.txt'), header + sections.join('\n'));
console.log(`dist/THIRD_PARTY_LICENSES.txt: ${sections.length} packages`);
for (const dir of [...packages.keys()].sort()) console.log(`  ${dir.slice(root.length + 1)}  ${packages.get(dir)} bytes`);
